"""Rewrite the metric lines of README.md, LAUNCH.md, CLAUDE.md, .cursorrules and the
quick-facts table of .stepcheck/HN-WAR-ROOM.md from receipts on disk, so no figure
in those files is typed by hand. Writes receipts/docs_sync.json listing every
substitution (file, pattern, old, new, source) for verify_integrity.py to re-check.

Sources: receipts/pytest_full.json (test count), receipts/repo_sync.json (LOC, audit
totals), benchmarks/results.json (benchmark figures).

Then publishes the generated artifacts: PAPER.md and docs/paper.tex from the paper
verify_integrity.py last wrote (run verify_integrity.py first), docs/index.html from
stepcheck-studio-preview.html, and docs/llms.txt + llms-full.txt via `stepcheck llms`.
"""
import datetime as dt
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
R = HERE / "receipts"

tests = json.load(open(R / "pytest_full.json", encoding="utf-8"))["passed"]
sync = json.load(open(R / "repo_sync.json", encoding="utf-8"))
final = json.load(open(REPO / "benchmarks" / "results.json", encoding="utf-8"))["final"]
loc = sync["loc"]["total"]
au = sync["docs_audit"]["total"]
loc_rounded = int(round(loc, -1))

subs = []


def apply(path: Path, pattern: str, repl: str, source: str, count_expected: int | None = None) -> None:
    text = path.read_text(encoding="utf-8")
    new, n = re.subn(pattern, repl, text)
    if count_expected is not None and n != count_expected:
        sys.exit(f"{path.name}: pattern {pattern!r} matched {n} times, expected {count_expected}")
    if n:
        path.write_text(new, encoding="utf-8")
    subs.append({"file": str(path.relative_to(REPO)).replace("\\", "/"), "pattern": pattern, "replacement": repl, "matches": n, "source": source})


# test counts
for f in ("README.md", "LAUNCH.md"):
    apply(REPO / f, r"\b\d{2,3} tests(?=,| at| must)", f"{tests} tests", "pytest_full.json:passed")
apply(REPO / "LAUNCH.md", r"\| Tests \| \d{2,3},", f"| Tests | {tests},", "pytest_full.json:passed")
apply(REPO / "LAUNCH.md", r"Expect `\d{2,3} passed`", f"Expect `{tests} passed`", "pytest_full.json:passed")
apply(REPO / "LAUNCH.md", r"(~[\d,]+ LOC, )\d{2,3} tests", f"\\g<1>{tests} tests", "pytest_full.json:passed")
for f in ("CLAUDE.md", ".cursorrules"):
    apply(REPO / f, r"\d{2,3} tests must pass", f"{tests} tests must pass", "pytest_full.json:passed")
apply(REPO / ".stepcheck" / "HN-WAR-ROOM.md", r"\| Tests \| \d{2,3} at two seams", f"| Tests | {tests} at two seams", "pytest_full.json:passed")
# LOC
apply(REPO / "LAUNCH.md", r"≈[\d,]+ LOC", f"≈{loc_rounded:,} LOC", "repo_sync.json:loc.total")
apply(REPO / "LAUNCH.md", r"~3,000 LOC", f"~{loc_rounded:,} LOC", "repo_sync.json:loc.total")
apply(REPO / "LAUNCH.md", r"about 3k lines", f"about {loc_rounded:,} lines", "repo_sync.json:loc.total")
# audit figures (published receipt regenerated by Slice 20): the previous values are
# read from LAUNCH.md's own audit row, so the sync works from any earlier snapshot.
row = re.search(r"\| Real-log audit \| (\d+) Claude Code sessions, ([\d,]+) assistant turns, (\d+) cache-cliff resumes "
                r"re-writing ([\d,]+) tokens, \$([\d.]+) paid", (REPO / "LAUNCH.md").read_text(encoding="utf-8"))
if row:
    prev_tokens = int(row.group(4).replace(",", ""))
    old = {"sessions": row.group(1), "turns": re.escape(row.group(2)), "gaps": row.group(3), "tokens": re.escape(row.group(4)),
           "tokens_m": re.escape(f"{prev_tokens / 1e6:.2f}M"), "usd": re.escape(row.group(5))}
else:
    old = {"sessions": r"116", "turns": r"5,330", "gaps": r"67", "tokens": r"4,950,678", "tokens_m": r"4\.95M", "usd": r"13\.37"}
new = {"sessions": f"{au['sessions']}", "turns": f"{au['assistant_turns']:,}", "gaps": f"{au['cache_gap_turns']}",
       "tokens": f"{au['gap_rebilled_tokens']:,}", "tokens_m": f"{au['gap_rebilled_tokens'] / 1e6:.2f}M", "usd": f"{au['gap_waste_usd']:.2f}"}
for f in ("README.md", "LAUNCH.md", ".stepcheck/HN-WAR-ROOM.md"):
    p = REPO / f
    apply(p, rf"\b{old['sessions']}(-| )session", f"{new['sessions']}\\1session", "repo_sync.json:audit.sessions")
    apply(p, rf"\b{old['sessions']} sessions", f"{new['sessions']} sessions", "repo_sync.json:audit.sessions")
    apply(p, rf"\b{old['sessions']} Claude Code sessions", f"{new['sessions']} Claude Code sessions", "repo_sync.json:audit.sessions")
    apply(p, rf"\b{old['turns']} (assistant turns|turns)", f"{new['turns']} \\1", "repo_sync.json:audit.assistant_turns")
    apply(p, rf"\b{old['gaps']} (cache-cliff|turns resumed|pauses|cache)", f"{new['gaps']} \\1", "repo_sync.json:audit.cache_gap_turns")
    apply(p, rf"\b{old['tokens']}\b", new["tokens"], "repo_sync.json:audit.gap_rebilled_tokens")
    apply(p, rf"\b{old['tokens_m']} tokens", f"{new['tokens_m']} tokens", "repo_sync.json:audit.gap_rebilled_tokens")
    apply(p, rf"\${old['usd']}\b", f"${new['usd']}", "repo_sync.json:audit.gap_waste_usd")
    apply(p, rf"\b{old['usd']} (paid|of cache)", f"{new['usd']} \\1", "repo_sync.json:audit.gap_waste_usd")
# benchmark figures: previous published values -> current results.json
prev = json.load(open(R / "benchmark_previous.json", encoding="utf-8")) if (R / "benchmark_previous.json").exists() else None
if prev and prev["final"] != {k: final[k] for k in prev["final"]}:
    pf = prev["final"]
    for f in ("README.md", "LAUNCH.md", ".stepcheck/HN-WAR-ROOM.md", "benchmarks/README.md"):
        p = REPO / f
        if not p.exists():
            continue
        if "raw_bloated_tokens" in pf:
            apply(p, rf"\b{pf['raw_bloated_tokens']:,}\b", f"{final['raw_bloated_tokens']:,}", "results.json:final.raw_bloated_tokens")
        apply(p, rf"\b{pf['compacted_okf_tokens']:,}\b", f"{final['compacted_okf_tokens']:,}", "results.json:final.compacted_okf_tokens")
        apply(p, rf"\b{pf['savings_pct']}%", f"{final['savings_pct']}%", "results.json:final.savings_pct")
        apply(p, rf"\b{pf['tokens_saved']:,}\b", f"{final['tokens_saved']:,}", "results.json:final.tokens_saved")
        apply(p, rf"\${pf['dollars_saved']:.4f}\b", f"${final['dollars_saved']:.4f}", "results.json:final.dollars_saved")
for f in ("README.md", "LAUNCH.md"):
    text = (REPO / f).read_text(encoding="utf-8")
    for needle, src in ((f"{final['compacted_okf_tokens']:,}", "results.json:final.compacted_okf_tokens"),
                        (f"{final['savings_pct']}%", "results.json:final.savings_pct")):
        subs.append({"file": f, "pattern": None, "replacement": needle, "matches": text.count(needle), "source": src, "check_only": True})

# Published copies of generated artifacts (run after the substitutions above, which
# llms-full.txt embeds). PAPER.md = the paper verify_integrity.py last generated plus
# the hand-written sections after it (from ABLATION_MARKER on, kept verbatim).
ABLATION_MARKER = "## 6. Head-to-Head Market Ablation"
published = []
paper_md, paper_tex = REPO / ".stepcheck" / "paper" / "STEPCHECK_PAPER.md", REPO / ".stepcheck" / "paper" / "stepcheck_paper.tex"
if paper_md.exists():
    current = (REPO / "PAPER.md").read_text(encoding="utf-8") if (REPO / "PAPER.md").exists() else ""
    tail = current[current.index(ABLATION_MARKER):] if ABLATION_MARKER in current else ""
    body = paper_md.read_text(encoding="utf-8").rstrip("\n") + "\n"
    (REPO / "PAPER.md").write_bytes((body + ("\n" + tail if tail else "")).encode("utf-8"))
    published.append({"file": "PAPER.md", "from": ".stepcheck/paper/STEPCHECK_PAPER.md", "kept_tail": bool(tail)})
if paper_tex.exists():
    (REPO / "docs" / "paper.tex").write_bytes(paper_tex.read_bytes())
    published.append({"file": "docs/paper.tex", "from": ".stepcheck/paper/stepcheck_paper.tex"})
preview = REPO / "stepcheck-studio-preview.html"
if preview.exists():
    (REPO / "docs" / "index.html").write_bytes(preview.read_bytes())
    published.append({"file": "docs/index.html", "from": "stepcheck-studio-preview.html"})
sys.path.insert(0, str(REPO / "backend"))
import cli  # noqa: E402

if cli.main(["llms", "--out", str(REPO / "docs")]) != 0:
    sys.exit("stepcheck llms failed")
published += [{"file": "docs/llms.txt", "from": "stepcheck llms"}, {"file": "docs/llms-full.txt", "from": "stepcheck llms"}]

(R / "docs_sync.json").write_text(json.dumps({
    "generated_at": dt.datetime.now(dt.timezone.utc).isoformat(), "generator": ".stepcheck/discovery/sync_docs.py",
    "values": {"tests": tests, "loc": loc, "loc_rounded": loc_rounded, "audit": au,
               "benchmark": {k: final[k] for k in ("raw_bloated_tokens", "compacted_okf_tokens", "savings_pct")}},
    "substitutions": subs,
    "published": published,
}, indent=1), encoding="utf-8")
print(json.dumps({"tests": tests, "loc": loc, "audit": au, "substitutions": sum(s["matches"] for s in subs)}))
